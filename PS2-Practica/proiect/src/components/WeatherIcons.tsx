export function WeatherCodeIcon({ code, isDay = 1, className = 'w-8 h-8' }: { code: number; isDay?: number; className?: string }) {
  if (code === 0) {
    return isDay ? <SunIcon className={className} /> : <MoonIcon className={className} />;
  }
  if (code === 1 || code === 2) {
    return <CloudSunIcon className={className} />;
  }
  if (code === 3) {
    return <CloudIcon className={className} />;
  }
  if (code === 45 || code === 48) {
    return <FogIcon className={className} />;
  }
  if (code >= 51 && code <= 65) {
    return code >= 65 ? <HeavyRainIcon className={className} /> : <RainIcon className={className} />;
  }
  if (code >= 71 && code <= 77) {
    return <SnowIcon className={className} />;
  }
  if (code >= 80 && code <= 82) {
    return <HeavyRainIcon className={className} />;
  }
  if (code >= 95) {
    return <ThunderIcon className={className} />;
  }
  return <SunIcon className={className} />;
}
